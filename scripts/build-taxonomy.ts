/**
 * Compiles /taxonomy/*.yaml into:
 *   - packages/core/src/taxonomy/generated.ts  (importable from Node, Vite and Deno edge functions)
 *   - supabase/seed.sql                         (taxonomy_keys rows)
 * `--check` exits non-zero if either output is stale.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { TaxonomyFileSchema } from "../packages/core/src/taxonomy/schema.ts";
import { CATEGORIES } from "../packages/core/src/types.ts";

const root = new URL("..", import.meta.url).pathname;
const taxDir = join(root, "taxonomy");
const tsOut = join(root, "packages/core/src/taxonomy/generated.ts");
const sqlOut = join(root, "supabase/seed.sql");

const files = readdirSync(taxDir).filter((f) => f.endsWith(".yaml")).sort();
const services = [];
const seenCategories = new Set<string>();
for (const f of files) {
  const parsed = TaxonomyFileSchema.safeParse(parse(readFileSync(join(taxDir, f), "utf8")));
  if (!parsed.success) {
    console.error(`taxonomy/${f} is invalid:\n${parsed.error.message}`);
    process.exit(1);
  }
  seenCategories.add(parsed.data.category);
  for (const s of parsed.data.services) services.push({ category: parsed.data.category, ...s });
}
const missing = CATEGORIES.filter((c) => !seenCategories.has(c));
if (missing.length) {
  console.error(`missing taxonomy files for: ${missing.join(", ")}`);
  process.exit(1);
}

const ts = `// GENERATED by scripts/build-taxonomy.ts from /taxonomy/*.yaml — do not edit by hand.
import type { TaxonomyService } from "./schema.ts";

export const TAXONOMY: readonly TaxonomyService[] = ${JSON.stringify(services, null, 2)};
`;

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const sql = `-- GENERATED by scripts/build-taxonomy.ts from /taxonomy/*.yaml — do not edit by hand.
insert into public.taxonomy_keys (key, category, label, unit) values
${services.map((s) => `  (${q(s.key)}, ${q(s.category)}, ${q(s.label)}, ${q(s.unit)})`).join(",\n")}
on conflict (key) do update set category = excluded.category, label = excluded.label, unit = excluded.unit;
`;

if (process.argv.includes("--check")) {
  const stale = [
    [tsOut, ts],
    [sqlOut, sql],
  ].filter(([p, c]) => !existsSync(p!) || readFileSync(p!, "utf8") !== c);
  if (stale.length) {
    console.error(`stale generated taxonomy: ${stale.map(([p]) => p).join(", ")} — run pnpm taxonomy:build`);
    process.exit(1);
  }
  console.log(`taxonomy up to date (${services.length} keys)`);
} else {
  writeFileSync(tsOut, ts);
  writeFileSync(sqlOut, sql);
  console.log(`wrote ${services.length} keys from ${files.length} files`);
}
